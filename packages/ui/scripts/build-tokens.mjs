// Converts the Figma Tokens JSON (tokens/tokens.json) into CSS custom properties.
import { readFileSync, writeFileSync } from 'node:fs'

const tokens = JSON.parse(readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8'))
const lines = []
const walk = (node, path) => {
  if (typeof node.value === 'string') lines.push(`  --bk-${path.join('-')}: ${node.value};`)
  else for (const [k, v] of Object.entries(node)) walk(v, [...path, k])
}
walk(tokens.global, [])
writeFileSync(
  new URL('../src/styles/tokens.css', import.meta.url),
  `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`,
)
console.log(`tokens: ${lines.length} custom properties`)
